import type { LineIconName } from '@/components/ui/LineIcon';
import { SITE_IMAGES, type SiteImage } from '@/constants/siteImages';

/**
 * The five service pages, one entry each.
 *
 * The copy is transcribed from the page designs Shiran sent (WhatsApp,
 * 21.9.2026) — hero, "למי השירות מתאים", what the service includes, how it
 * works, and the closing note. <ServiceDetail> renders whichever blocks an
 * entry defines, so a page that has no checklist or no note simply omits it.
 *
 * The FAQ answers are the one thing the designs do not contain: the accordions
 * are drawn closed, so only the questions are hers. The answers below are
 * drafts — deliberately free of prices and fixed timelines — and need her
 * approval before this goes live.
 */

export interface ServiceFeature {
  icon: LineIconName;
  title: string;
  description: string;
}

export interface ServiceStep {
  title: string;
  description: string;
}

export interface ServiceFaq {
  question: string;
  answer: string;
}

export interface ServicePage {
  /** The URL, without a leading slash. Also the key used everywhere else. */
  slug: string;
  /** H1, and the label on the services grid. */
  title: string;
  /** Under the H1 in the hero. */
  subtitle: string;
  /** The short vertical tagline at the far edge of the hero, one line each. */
  tagline?: string[];
  hero: SiteImage;
  /** The card photo on /services and the home grid. */
  cardImage: SiteImage;
  /** One line under the title in the services grid. */
  cardDescription: string;
  icon: LineIconName;
  /** "למי השירות מתאים?" — the heading, then a paragraph per entry. */
  intro: { title: string; body: string[]; image: SiteImage };
  includes: { title: string; subtitle?: string; items: ServiceFeature[] };
  steps: { title: string; subtitle: string; items: ServiceStep[] };
  /** The ticked list ("למה חשוב…", "מה תקבלו…"), where the design has one. */
  checklist?: { title: string; body?: string; items: string[]; image: SiteImage };
  /** "טוב לדעת" / "טיפ ממני" — signed, on a soft panel. */
  note?: { title: string; body: string };
  faq: ServiceFaq[];
  /** The design shows a projects strip on these two pages. */
  showProjects?: boolean;
  cta: { title: string; subtitle: string };
}

